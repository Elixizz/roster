#!/usr/bin/env python3
"""Rebuild free-agency/data/players.js from nflverse's weekly NFL rosters.

Usage:  python3 tools/update_players.py [season]

Takes each team's most recent game-day roster and keeps players whose
status is ACT (active) or INA (inactive for the game but still on the
53-man roster). Practice squad, injured reserve and released players are
left out. Note: practice squad players elevated for that game are also
marked ACT, so a team can show up to 55 or so.
"""
import csv, io, json, sys, urllib.request
from collections import defaultdict
from datetime import date

season = int(sys.argv[1]) if len(sys.argv) > 1 else date.today().year
url = f"https://github.com/nflverse/nflverse-data/releases/download/weekly_rosters/roster_weekly_{season}.csv"
rows = list(csv.DictReader(io.StringIO(urllib.request.urlopen(url).read().decode("utf-8"))))

latest = defaultdict(int)
for r in rows:
    latest[r["team"]] = max(latest[r["team"]], int(r["week"]))

# nflverse position / depth chart position -> our positions
DEPTH = {"QB": "QB", "RB": "RB", "FB": "RB", "WR": "WR", "TE": "TE",
         "C": "C", "G": "G", "LG": "G", "RG": "G", "T": "T", "LT": "T", "RT": "T",
         "DE": "DE", "DT": "DT", "NT": "DT",
         "OLB": "LB", "ILB": "LB", "MLB": "LB", "LB": "LB",
         "CB": "CB", "SS": "S", "FS": "S", "S": "S", "DB": "CB",
         "K": "K", "P": "P", "LS": "LS"}
FALLBACK = {"OL": "G", "DL": "DT", "DB": "CB"}

players = []
for r in rows:
    if int(r["week"]) != latest[r["team"]] or r["status"] not in ("ACT", "INA"):
        continue
    pos = DEPTH.get(r["depth_chart_position"]) or DEPTH.get(r["position"]) or FALLBACK.get(r["position"])
    if not pos:
        print("skipping (unknown position):", r["full_name"], r["position"], file=sys.stderr)
        continue
    photo = r["headshot_url"].rsplit("/", 1)[-1] if "static.www.nfl.com" in r["headshot_url"] else ""
    players.append({"name": r["full_name"], "pos": pos, "team": r["team"],
                    "num": r["jersey_number"], "photo": photo})

players.sort(key=lambda p: (p["team"], p["name"]))
weeks = sorted(set(latest.values()))
header = f"""// GENERATED by tools/update_players.py from nflverse weekly rosters
// ({season} season, week {weeks[-1] if len(weeks) == 1 else f'{weeks[0]}-{weeks[-1]}'}). Every player on an NFL 53-man roster.
// Re-run that script to refresh; hand edits will be overwritten.
//   name, pos (QB RB WR TE C G T DE DT LB CB S K P LS), team, num (jersey),
//   photo (NFL headshot id: static.www.nfl.com/image/upload/.../league/<photo>)
"""
body = ",\n".join(json.dumps(p, ensure_ascii=False, separators=(",", ":")) for p in players)
with open("free-agency/data/players.js", "w", encoding="utf-8") as f:
    f.write(header + f"window.FREE_AGENTS_UPDATED = {json.dumps(f'{season} season, week {weeks[-1]}')};\n")
    f.write("window.FREE_AGENTS = [\n" + body + "\n];\n")
print(len(players), "players from", len(latest), "teams")
