#!/usr/bin/env python3
"""Rebuild free-agency/data/players.js: every player on an NFL 53-man roster.

Usage:  python3 tools/update_players.py [season]

Source: nflverse (https://github.com/nflverse/nflverse-data), which mirrors
the NFL's official player transactions and is refreshed daily.
  - players.csv gives each player's current team and roster status. We keep
    status ACT (on the 53-man roster). Practice squad (DEV), injured reserve
    (RES), PUP, suspended and released players are left out.
  - If a team still shows more than 53, players NFL Next Gen Stats lists as
    practice squad / reserve (game-day call-ups) are removed.
  - The weekly roster file supplies detailed positions (e.g. OLB vs ILB).
Teams with an open roster spot can legitimately show 51 or 52.
"""
import csv, io, json, sys, urllib.request
from collections import Counter, defaultdict
from datetime import date

season = sys.argv[1] if len(sys.argv) > 1 else str(date.today().year)
BASE = "https://github.com/nflverse/nflverse-data/releases/download/"

def fetch(path):
    return list(csv.DictReader(io.StringIO(urllib.request.urlopen(BASE + path).read().decode("utf-8"))))

players = fetch("players/players.csv")
weekly = fetch(f"weekly_rosters/roster_weekly_{season}.csv")

depth = {}
for r in sorted(weekly, key=lambda r: int(r["week"])):
    if r["depth_chart_position"]:
        depth[r["gsis_id"]] = r["depth_chart_position"]

MAP = {"QB": "QB", "RB": "RB", "FB": "RB", "HB": "RB", "WR": "WR", "TE": "TE",
       "C": "C", "G": "G", "OG": "G", "LG": "G", "RG": "G", "T": "T", "OT": "T", "LT": "T", "RT": "T",
       "DE": "DE", "DT": "DT", "NT": "DT",
       "LB": "LB", "OLB": "LB", "ILB": "LB", "MLB": "LB",
       "CB": "CB", "S": "S", "SS": "S", "FS": "S", "SAF": "S",
       "K": "K", "PK": "K", "P": "P", "LS": "LS"}
FALLBACK = {"OL": "G", "DL": "DT", "DB": "CB"}

roster = [p for p in players if p["last_season"] == season and p["status"] == "ACT" and p["latest_team"]]
by_team = defaultdict(list)
for p in roster:
    by_team[p["latest_team"]].append(p)
for team, ps in by_team.items():
    if len(ps) > 53:
        by_team[team] = [p for p in ps if p["ngs_status"] not in ("DEV", "RES", "CUT")]

out = []
for team, ps in by_team.items():
    for p in ps:
        pos = MAP.get(depth.get(p["gsis_id"], "")) or MAP.get(p["position"]) or FALLBACK.get(p["position"])
        if not pos:
            print("skipping (unknown position):", p["display_name"], p["position"], file=sys.stderr)
            continue
        nfl_photo = p["headshot"].rsplit("/", 1)[-1] if "static.www.nfl.com" in p["headshot"] else ""
        out.append({"name": p["display_name"], "pos": pos, "team": team, "num": p["jersey_number"],
                    "espn": p["espn_id"], "photo": nfl_photo})

out.sort(key=lambda p: (p["team"], p["name"]))
counts = Counter(p["team"] for p in out)
stamp = f"Updated {date.today():%b %-d, %Y}"
header = f"""// GENERATED by tools/update_players.py from nflverse ({season} season). {stamp}.
// Every player on an NFL 53-man roster. Re-run that script to refresh; hand edits will be overwritten.
//   name, pos (QB RB WR TE C G T DE DT LB CB S K P LS), team, num (jersey),
//   espn (ESPN player id, used for the headshot), photo (NFL.com headshot id, backup)
"""
body = ",\n".join(json.dumps(p, ensure_ascii=False, separators=(",", ":")) for p in out)
with open("free-agency/data/players.js", "w", encoding="utf-8") as f:
    f.write(header + f"window.FREE_AGENTS_UPDATED = {json.dumps(stamp)};\n")
    f.write("window.FREE_AGENTS = [\n" + body + "\n];\n")
print(len(out), "players;", "teams not at 53:", {t: n for t, n in sorted(counts.items()) if n != 53} or "none")
